def get_states():
    """Return sorted list of all Indian states and UTs."""
    return sorted(INDIA_GEO.keys())


def get_districts(state: str):
    """Return sorted list of districts for a given state."""
    state_data = INDIA_GEO.get(state, {})
    return sorted(state_data.keys())


def get_blocks(state: str, district: str):
    """Return sorted list of blocks/talukas/mandals for a given state and district."""
    state_data = INDIA_GEO.get(state, {})
    return sorted(state_data.get(district, []))
